/** Layout only. Code owns questions, applicability, answers and review semantics. */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const LAYOUT_END = "<!-- /repo-template-pr-layout -->";

interface Producer {
  renderPrTemplate: () => string;
  PR_ATTESTATION_CONTRACT_DIGEST: string;
}
function isProducer(value: unknown): value is Producer {
  return typeof value === "object" && value !== null &&
    "renderPrTemplate" in value && typeof value.renderPrTemplate === "function" &&
    "PR_ATTESTATION_CONTRACT_DIGEST" in value && typeof value.PR_ATTESTATION_CONTRACT_DIGEST === "string";
}

export async function renderPortablePrTemplate(codeRoot: string): Promise<string> {
  // Explicit caller-selected checkout; never fetch, choose a credential, or silently fall back.
  const producer: unknown = await import(pathToFileURL(path.join(codeRoot, "contracts/pr-attestation.ts")).href);
  if (!isProducer(producer)) throw new Error("Code PrAttestation producer API is unavailable");
  const contract = fs.readFileSync(path.join(codeRoot, "contracts/pr-attestation.v1.json"));
  const expectedDigest = `sha256:${createHash("sha256").update(JSON.stringify(JSON.parse(contract.toString("utf8")))).digest("hex")}`;
  if (producer.PR_ATTESTATION_CONTRACT_DIGEST !== expectedDigest) throw new Error("Code producer and contract identity disagree");
  const block = producer.renderPrTemplate().split("\n").map((line) => line.trimEnd()).join("\n");
  if (!block.startsWith("<!-- governed-pr-attestation:v1 -->") ||
      !block.trimEnd().endsWith("<!-- /governed-pr-attestation:v1 -->")) {
    throw new Error("Code producer returned an invalid attestation block");
  }
  return `<!-- Generated by tools/pr-attestation-template.ts from Code's public producer.\nConsumed contract: ${expectedDigest}\nThis is provenance, not a frozen revision or an approval. -->\n\n` +
    block + `\n\n## Conditional required acceptance\n\nThe governed PR creation path replaces the pending block using Code's current applicability and\nauthor answers. It adds only relevant required concerns; do not answer a wall of unrelated N/A\nquestions. A pending template does not claim a candidate classification or reviewer agreement.\n\n## Suggested review prompts\n\n<details>\n<summary>Advisory reviewer attention</summary>\n\nUse Code's canonical attestation concerns when an additional issue is relevant. Suggestions are\nadvisory; promoting one to required work belongs to the governed PR tooling, which regenerates the\nrequired block. Repository-specific context may be appended outside that block.\n\n</details>\n${LAYOUT_END}\n`;
}

export async function checkPortablePrTemplate(codeRoot: string, templatePath: string): Promise<boolean> {
  const text = fs.readFileSync(templatePath, "utf8");
  return text.startsWith(await renderPortablePrTemplate(codeRoot)) &&
    (text.match(/<!-- governed-pr-attestation:v1 -->/g) ?? []).length === 1;
}

export async function writePortablePrTemplate(codeRoot: string, templatePath: string): Promise<void> {
  const current = fs.existsSync(templatePath) ? fs.readFileSync(templatePath, "utf8") : "";
  const end = current.indexOf(LAYOUT_END);
  const local = end < 0 ? "" : current.slice(end + LAYOUT_END.length).replace(/^\n/, "");
  fs.writeFileSync(templatePath, await renderPortablePrTemplate(codeRoot) + local);
}

async function main(): Promise<void> {
  const codeFlag = process.argv.find((arg) => arg.startsWith("--code-root="));
  if (!codeFlag) throw new Error("Pass --code-root=<actual Code checkout>; no implicit source or network fallback");
  const codeRoot = path.resolve(codeFlag.slice("--code-root=".length));
  const templatePath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../.github/pull_request_template.md");
  if (process.argv.includes("--write")) await writePortablePrTemplate(codeRoot, templatePath);
  else if (!await checkPortablePrTemplate(codeRoot, templatePath)) {
    throw new Error("Portable PR template differs from the selected current Code producer; review and regenerate the projection");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
